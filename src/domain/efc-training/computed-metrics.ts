// ─── 1RM calculation ──────────────────────────────────────────────────────────

/**
 * Output of `computeOneRm` for a single lift input.
 *
 * - `repsTotal`         — repsPerformed + rir (effective reps for formula input)
 * - `epley`             — Epley estimate: weight × (1 + repsTotal / 30)
 * - `brzycki`           — Brzycki estimate; null when repsTotal ≥ 37 (denominator ≤ 0)
 * - `average`           — (epley + brzycki) / 2; falls back to epley when brzycki is null
 * - `unreliableWarning` — true when repsTotal > 30 (accuracy degrades beyond this point)
 */
export interface OneRmResult {
  repsTotal: number;
  epley: number;
  brzycki: number | null;
  average: number;
  unreliableWarning: boolean;
}

/**
 * A single row of the 1RM percentage lookup table.
 * Generated by `computeOneRmPercentageTable` for percentages 50 %–100 % in steps of 5.
 */
export interface OneRmPercentageRow {
  /** Percentage of 1RM (50, 55, 60, …, 100). */
  percentage: number;
  /** Corresponding weight in kg, rounded to nearest 0.5 kg. */
  weightKg: number;
  /** Estimated repetitions to failure at this intensity (Epley inverted, rounded). */
  repsToFailure: number;
}

/**
 * EFC-period–specific loading prescription derived from a computed 1RM.
 * Produced by `computeEfcPrescription` for each of the three EFC phases.
 */
export interface OneRmEfcRecommendation {
  period: EfcPeriod;
  /** Lower bound of the recommended intensity range (% of 1RM). */
  percentageMin: number;
  /** Upper bound of the recommended intensity range (% of 1RM). */
  percentageMax: number;
  /** Minimum recommended weight in kg (derived from percentageMin × 1RM). */
  weightMin: number;
  /** Maximum recommended weight in kg (derived from percentageMax × 1RM). */
  weightMax: number;
  /** Suggested sets range, e.g. "3–5". */
  seriesRange: string;
  /** Suggested reps range, e.g. "6–8". */
  repsRange: string;
  /** Suggested RIR range, e.g. "1–2". */
  rirRange: string;
  /** Short description of the training focus for this period. */
  focus: string;
}

// ─── Foster monotony ──────────────────────────────────────────────────────────

/**
 * Foster's monotony and strain metrics for a 7-day training week.
 *
 * - `weeklyLoad`          — sum of sRPE × duration for all 7 days
 * - `dailyMean`           — weeklyLoad / 7
 * - `dailySD`             — population SD of daily loads; null when all values are equal
 * - `monotony`            — dailyMean / dailySD; null when SD = 0
 * - `strain`              — weeklyLoad × monotony; null when monotony is null
 * - `highMonotonyWarning` — true when monotony > 2.0
 */
export interface FosterMonotonyResult {
  weeklyLoad: number;
  dailyMean: number;
  dailySD: number | null;
  monotony: number | null;
  strain: number | null;
  highMonotonyWarning: boolean;
}

// ─── Macrocycle distribution ──────────────────────────────────────────────────

/**
 * Full computed volume distribution for a planned macrocycle.
 * Produced by combining F-01, F-02, F-03, F-04, F-05, F-06 formula results.
 */
export interface MacrocycleDistribution {
  totalDays: number;
  totalWeeks: number;
  totalMinutes: number;
  totalHours: number;
  /** Minutes allocated to Estructura period. */
  estructuraMinutes: number;
  /** Minutes allocated to Función period. */
  funcionMinutes: number;
  /** Minutes allocated to Cognición period. */
  cognicionMinutes: number;
  /** Weeks allocated to Estructura period. */
  estructuraSemanas: number;
  /** Weeks allocated to Función period. */
  funcionSemanas: number;
  /** Weeks allocated to Cognición period. */
  cognicionSemanas: number;
  /** Microcycle type week counts across the full macrocycle. */
  tiposMicrociclo: {
    ajuste: number;
    carga: number;
    impacto: number;
    activacion: number;
    competencia: number;
    recuperacion: number;
  };
}
