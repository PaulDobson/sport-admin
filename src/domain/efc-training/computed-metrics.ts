// ─── Physiological metrics ────────────────────────────────────────────────────

/**
 * Result of computing all physiological indicators from an athlete's
 * baseline data (age, weight, height, gender, FCRest, Cooper distance).
 * Any field can be null when input data required for that formula is absent.
 */
export interface PhysiologicalMetrics {
  /** Body Mass Index (kg / m²). Null if weight or height is missing. */
  imc: number | null;
  imcClassification: ImcClassification | null;
  /** Maximum heart rate estimate — Tanaka et al. formula: 208 − 0.7 × age. */
  fcMax: number | null;
  /** Total metabolic rate in kcal/day — Mifflin–St Jeor formula. */
  tmb: number | null;
  /** Heart Rate Reserve (Karvonen): FCMax − FCRest. */
  fcr: number | null;
  /** VO2max estimate from Cooper test: (distance − 504.9) / 44.73. */
  vo2max: number | null;
  /** Estimated daily caloric expenditure (kcal/day) derived from TMB and activity factor. */
  estimatedDailyCalories: number | null;
}

// ─── ACWR ─────────────────────────────────────────────────────────────────────

/** Acute:Chronic Workload Ratio zone classification. */
export type AcwrZone = 'undertrained' | 'optimal' | 'caution' | 'danger';

/**
 * Full result of the ACWR calculation for a given 28-day sRPE window.
 *
 * - `ca`                — 7-day rolling mean of daily sRPE (acute load)
 * - `cc`                — 28-day rolling mean (chronic load)
 * - `acwr`              — ratio CA / CC; null when CC = 0
 * - `zone`              — null when acwr is null
 * - `insufficientData`  — true when fewer than 28 days of records are available
 */
export interface AcwrResult {
  ca: number;
  cc: number;
  acwr: number | null;
  zone: AcwrZone | null;
  insufficientData: boolean;
  daysOfData: number;
}

