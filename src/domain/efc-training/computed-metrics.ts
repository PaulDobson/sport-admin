/**
 * Domain: EFC Training
 *
 * Types and constants for computed / derived values that are calculated on the
 * fly from stored entity data and are never persisted to the database.
 *
 *   - PhysiologicalMetrics    — BMI, FCMax, TMB, FCR, VO2max
 *   - AcwrResult              — acute:chronic workload ratio with zone classification
 *   - OneRmResult             — Epley / Brzycki / average 1RM calculation output
 *   - OneRmPercentageRow      — a single row of the 1RM percentage table
 *   - OneRmEfcRecommendation  — per-EFC-period loading prescription
 *   - FosterMonotonyResult    — Foster's monotony and strain indicators
 *   - MacrocycleDistribution  — full volume breakdown for a planned macrocycle
 */

